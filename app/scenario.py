# Поддерживаемые пользовательские фразы обновления. После маркера идёт одно значение.
_UPDATE_PATTERNS = (
    ('срок', r'(?:срок (?:теперь|переносим на|перенесли на)|сдвинули срок на)'),
    ('статус', r'статус теперь'),
    ('требование', r'требование теперь'),
    ('подход', r'(?:подход теперь|(?:новый|выбрали другой) подход)'),
    ('версия', r'версия теперь'),
)


def parse_update(text):
    if re.fullmatch(r'требование отменили[.!]?', text, re.IGNORECASE):
        return 'требование', 'отменено'
    for key, phrase in _UPDATE_PATTERNS:
        match = re.fullmatch(phrase + r'(?:\s*[:—-]\s*|\s+)(.+)', text, re.IGNORECASE)
        if match:
            value = match[1].removesuffix('.').strip()
            if value:
                return key, value
    return None


